using MarkInDeDark.LevelEditor.Domain;
using Newtonsoft.Json;
using System;
using System.Collections.Generic;
using System.IO;

namespace MarkInDeDark.Common
{
    public class TextFileStringsManager
    {
        private readonly TraslatedStrings _traslatedStrings;
        public string DefaultPathForSave { get; set; }

        public TextFileStringsManager(string rawTranslations)
        {
            _traslatedStrings = JsonConvert.DeserializeObject<TraslatedStrings>(rawTranslations);
        }

        public void Save(string filePath = null)
        {
            if (DefaultPathForSave != null)
                File.WriteAllText(DefaultPathForSave, JsonConvert.SerializeObject(_traslatedStrings));
            if (filePath != null)
                File.WriteAllText(filePath, JsonConvert.SerializeObject(_traslatedStrings));
        }

        public string GetString(StringsTraslationLanguages language, string key)
        {
            if (!_traslatedStrings.Traslations.ContainsKey(language))
                throw new ArgumentException($"No traslations found for {language}");
            if (!_traslatedStrings.Traslations[language].ContainsKey(key))
                throw new ArgumentException($"No text found for {language}, {key}");

            return _traslatedStrings.Traslations[language][key].Text;
        }

        public void SetString(StringsTraslationLanguages language, string key, TraslatedStringValue value)
        {
            if (!_traslatedStrings.Traslations.ContainsKey(language))
                throw new ArgumentException($"No traslations found for {language}");

            _traslatedStrings.Traslations[language][key] = value;
        }

        public void RemoveStringForAllLanguages(string key)
        {
            foreach (var language in _traslatedStrings.Traslations.Values)
                if (language.ContainsKey(key))
                    language.Remove(key);
        }

        public TraslatedStrings GetAllTranslations()
        {
            return _traslatedStrings;
        }

        public Dictionary<string, TraslatedStringValue> GetTranslations(StringsTraslationLanguages language)
        {
            if (!_traslatedStrings.Traslations.ContainsKey(language))
                throw new ArgumentException($"No traslations found for {language}");

            return _traslatedStrings.Traslations[language];
        }

        public string SetAutomaticKeyStringOnAllLanguages(string text)
        {
            string autogeneratedKey = DateTime.Now.Ticks.ToString();

            foreach (var language in _traslatedStrings.Traslations)
                language.Value[autogeneratedKey] = new TraslatedStringValue() { Text = text };

            return autogeneratedKey;
        }
    }
}
